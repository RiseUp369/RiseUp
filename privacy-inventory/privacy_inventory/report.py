"""Markdown governance record. Always a DRAFT for the owner; it approves nothing.

Every string taken from an inventory passes through `scrub`, so a name, email or
phone number that slipped into an inventory does not reach the record.
"""
from __future__ import annotations

import re

from privacy_inventory.checks import ERROR, REVIEW_REQUIRED, WARNING, counts
from privacy_inventory.retention import POLICY_LABEL
from privacy_inventory.steward import role_label_problems

BANNER = "# DRAFT – needs owner decision"

_PATTERNS = [
    re.compile(r"[^\s|`]*@[^\s|`]*"),
    re.compile(r"\+?\d(?:[\s().-]?\d){8,}"),  # 9+ digits: phones, not ISO dates
    re.compile(r"\b[A-Z][a-z]+(?:[ \t]+[A-Z][a-z]+)+\b"),
]


def scrub(text) -> str:
    if text is None:
        return "—"
    out = str(text)
    for pat in _PATTERNS:
        out = pat.sub("[redacted]", out)
    return out


def _cell(text) -> str:
    return scrub(text).replace("|", "\\|").replace("\n", " ")


def _steward_cell(field: dict, store: dict) -> str:
    label = field.get("steward_role") or store.get("steward_role")
    if not label:
        return "—"
    if role_label_problems(label):
        return "[not a role label – redacted]"
    return _cell(label)


def render_report(inventory: dict, findings: list, source: str, generated_on: str,
                  retention_results: list | None = None, as_of: str | None = None,
                  policy_label: str = POLICY_LABEL) -> str:
    c = counts(findings)
    lines = [
        BANNER,
        "",
        "> Generated by privacy-inventory as governance evidence. This record approves nothing:",
        "> every gap and review item below waits for an owner decision. Role labels only, no names.",
        "",
        f"- system: {_cell(inventory.get('system'))}",
        f"- inventory source: `{_cell(source)}`",
        f"- generated on: {_cell(generated_on)}",
        f"- synthetic inventory: {'yes' if inventory.get('synthetic') else 'no'}",
        f"- findings: {c[ERROR]} error(s), {c[REVIEW_REQUIRED]} review-required, {c[WARNING]} warning(s)",
        "",
        "## Owner decisions needed",
        "",
    ]
    review = [f for f in findings if f.severity == REVIEW_REQUIRED]
    if review:
        for f in review:
            lines.append(f"- [ ] `{_cell(f.source)}#{_cell(f.path)}` – {_cell(f.message)} ({f.code})")
    else:
        lines.append("- none flagged by the checker")
    lines += [
        "- [ ] confirm or replace the retention defaults below",
        "",
        "## Gaps (every finding)",
        "",
        "| severity | code | source path | detail |",
        "| --- | --- | --- | --- |",
    ]
    for f in findings:
        lines.append(f"| {f.severity} | {f.code} | `{_cell(f.source)}#{_cell(f.path)}` | {_cell(f.message)} |")
    if not findings:
        lines.append("| — | — | — | no gaps found |")

    lines += [
        "",
        "## Field inventory",
        "",
        "| store | field | classification | visibility | retention | steward role | processor | export |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for store in inventory.get("stores", []):
        proc = store.get("processor") or {}
        for field in store.get("fields", []):
            location = field.get("processor_location") or proc.get("location")
            lines.append(
                f"| {_cell(store.get('id'))} | {_cell(field.get('name'))} | {_cell(field.get('classification'))} "
                f"| {_cell(field.get('visibility'))} | {_cell(field.get('retention'))} "
                f"| {_steward_cell(field, store)} | {_cell(location)} "
                f"| {'yes' if field.get('export_eligible') else 'no'} |"
            )

    lines += ["", "## Retention", "", f"Policy: {policy_label}.", ""]
    if retention_results is None:
        lines.append("No records were supplied; run `retention --as-of DATE records.json` for per-record decisions.")
    else:
        lines += [f"As of {_cell(as_of)}:", "", "| record id | decision | reason |", "| --- | --- | --- |"]
        for r in retention_results:
            lines.append(f"| {_cell(r['id'])} | {r['decision']} | {_cell(r['reason'])} |")
    lines += [
        "",
        "## Notes",
        "",
        "- world-model v2 exports may carry only reviewed, de-identified learning; raw operations,",
        "  commitments and private context stay home.",
        "- raw access codes and secrets are never stored; hashes only.",
        "- a named data-steward role is still needed for copies held by outside services (owner names people).",
        "",
    ]
    return "\n".join(lines)
